def get(path):
    """Описание настройки или ``None``, если её нет в словаре."""
    item = DOCS.get(path)
    return dict(item) if isinstance(item, dict) else None


def paths():
    """Все документированные пути, по алфавиту."""
    return sorted(DOCS)


def search(query, limit=40):
    """Документированные пути, подходящие под запрос.

    Ищем и по пути, и по тексту: модель спрашивает «таймаут пробы», а
    не «blockcheck.probe_timeout». Совпадения в пути — первыми: точное
    имя ключа важнее упоминания в чужом описании.
    """
    needle = (query or "").strip().lower()
    if not needle:
        return paths()[:limit]
    in_path, in_text = [], []
    for path in paths():
        item = DOCS[path]
        if needle in path.lower():
            in_path.append(path)
            continue
        haystack = " ".join(str(item.get(key, ""))
                            for key in ("text", "unit", "empty"))
        if needle in haystack.lower():
            in_text.append(path)
    return (in_path + in_text)[:limit]
