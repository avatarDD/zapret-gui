"""
Описания настроек ``settings.json`` для модели: что делает ключ, в чём
измеряется и **что означает 0 или пустое значение**.

Это **данные, а не код**: словарь :data:`DOCS`, ключ — точечный путь.
Тип, значение по умолчанию и текущее значение здесь НЕ дублируются —
их берут живьём из ``DEFAULT_CONFIG``/``ConfigManager`` (см.
``core/mcp/tools/docs.py``). Записанный сюда дефолт разошёлся бы с
настоящим в первую же правку конфига и врал бы модели.

Зачем вообще:

* без описания модель угадывает смысл поля по имени — и «0» читает как
  «выключено» там, где это «без ограничения» (и наоборот);
* отказ ``config_set`` (S6) ссылается сюда: «поле закрыто на запись,
  вот что оно делает и чем его заменить».

**Нет описания — так и отвечаем.** ``config_describe`` не выдумывает
текст по имени ключа: он честно говорит «описания нет» и перечисляет
документированные рядом. Пустая строка в словаре хуже отсутствия:
она выглядит как описание.

Поля записи:

``text``
    Что делает настройка. По-русски, 1–3 предложения.
``unit``
    В чём измеряется (секунды, минуты, МиБ, список портов…). Без
    единицы число читается как попало.
``empty``
    Что означает ``0``/``""``/пустой список. Самое частое место, где
    модель ошибается.
``see``
    Соседние пути, которые имеет смысл прочитать вместе с этим.
"""


